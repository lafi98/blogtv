/**
 * Image handling: validates uploads by their actual bytes (not the client-supplied type),
 * strips metadata, and writes responsive WebP variants + a JPEG for social sharing.
 * File names are content-hashed, so they can be cached forever.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import sharp from 'sharp';
import { config } from '../config';
import { insertImage, type ImageVariant } from '../repos/images';
import { getDb } from '../db';

export const MAX_UPLOAD_BYTES = 10 * 1024 * 1024;
const WIDTHS = [480, 800, 1200];
const RASTER_FORMATS = new Set(['jpeg', 'png', 'webp', 'avif', 'gif']);

export interface ImageMeta {
  alt: string;
  caption?: string;
  credit?: string;
  license: string;
  sourceUrl?: string;
  originalName?: string;
}

export interface StoreOptions {
  /** Only for SVGs generated by this codebase (covers). Uploaded SVGs are rejected. */
  trustedSvg?: boolean;
}

export function uploadsDir(): string {
  fs.mkdirSync(config.uploadsDir, { recursive: true });
  return config.uploadsDir;
}

/** Process an image buffer into variants and register it in the media library. */
export async function storeImage(input: Buffer, meta: ImageMeta, opts: StoreOptions = {}): Promise<number> {
  if (input.length > MAX_UPLOAD_BYTES) throw new Error('Image is larger than 10 MB.');
  let probe: Awaited<ReturnType<ReturnType<typeof sharp>['metadata']>>;
  try {
    probe = await sharp(input, { limitInputPixels: 50_000_000 }).metadata();
  } catch {
    throw new Error('File is not a readable image.');
  }
  const okFormat = probe.format && (RASTER_FORMATS.has(probe.format) || (probe.format === 'svg' && opts.trustedSvg));
  if (!okFormat) throw new Error(`Unsupported image format: ${probe.format ?? 'unknown'}. Use JPEG, PNG, WebP, AVIF or GIF.`);

  const hash = crypto.createHash('sha256').update(input).digest('hex').slice(0, 12);
  const base = (meta.originalName ?? 'image')
    .replace(/\.[a-z0-9]+$/i, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 40) || 'image';
  const fileKey = `${base}-${hash}`;
  // Same name + same bytes = same image: reuse the existing record instead of duplicating it.
  const existing = getDb().prepare('SELECT id FROM images WHERE file_key = ?').get(fileKey) as { id: number } | undefined;
  if (existing) return existing.id;
  const dir = uploadsDir();

  // .rotate() applies EXIF orientation; metadata (incl. GPS) is not copied to outputs.
  const pipeline = () => sharp(input, { limitInputPixels: 50_000_000, density: probe.format === 'svg' ? 144 : undefined }).rotate();
  const { width: srcW = 1200 } = await pipeline().toBuffer({ resolveWithObject: true }).then((r) => r.info);

  const variants: ImageVariant[] = [];
  for (const w of WIDTHS) {
    if (w > srcW && variants.length) break;
    const targetW = Math.min(w, srcW);
    const file = `${fileKey}-${targetW}.webp`;
    const info = await pipeline().resize({ width: targetW, withoutEnlargement: true }).webp({ quality: 78, effort: 5 }).toFile(path.join(dir, file));
    variants.push({ w: info.width, h: info.height, file });
  }
  const ogFile = `${fileKey}-og.jpg`;
  await pipeline()
    .resize({ width: 1200, height: 630, fit: 'cover', position: 'attention' })
    .flatten({ background: '#faf6f0' })
    .jpeg({ quality: 82, mozjpeg: true })
    .toFile(path.join(dir, ogFile));

  const largest = variants[variants.length - 1];
  return insertImage({
    fileKey,
    originalName: meta.originalName ?? '',
    width: largest.w,
    height: largest.h,
    alt: meta.alt.trim(),
    caption: meta.caption?.trim() ?? '',
    credit: meta.credit?.trim() ?? '',
    license: meta.license.trim(),
    sourceUrl: meta.sourceUrl?.trim() ?? '',
    variants,
    ogFile,
  });
}

export function deleteImageFiles(fileNames: string[]) {
  const dir = uploadsDir();
  for (const f of fileNames) {
    if (!/^[a-z0-9-]+\.(webp|jpg)$/.test(f)) continue;
    fs.rmSync(path.join(dir, f), { force: true });
  }
}

/** srcset helper for <img>. */
export function srcset(variants: ImageVariant[]): string {
  return variants.map((v) => `/media/${v.file} ${v.w}w`).join(', ');
}
