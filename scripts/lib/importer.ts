import fs from 'node:fs';
import { parse as parseYaml } from 'yaml';
import { getDb, nowIso } from '../../src/lib/db';
import { getArticleBySlug, saveArticle, setValidation, getArticle } from '../../src/lib/repos/articles';
import { getCategoryBySlug } from '../../src/lib/repos/categories';
import { listAuthors } from '../../src/lib/repos/authors';
import { storeImage } from '../../src/lib/images/process';
import { COVER_MOTIFS, coverAlt, coverSvg } from '../../src/lib/images/covers';
import { articleToValidationInput, buildValidationContext } from '../../src/lib/publishing/context';
import { validateArticleSync } from '../../src/lib/publishing/validator';
import { SLUG_RE } from '../../src/lib/content/text';

interface FrontMatter {
  title: string;
  slug: string;
  category: string;
  tags?: string[];
  excerpt: string;
  seoTitle?: string;
  metaDescription?: string;
  cover?: string;
  related?: string[];
  faq?: { q: string; a: string }[];
  publishedAt?: string;
  aiAssisted?: boolean;
  reviewedBy?: string;
}

export function readMarkdown(file: string): { fm: FrontMatter; body: string } {
  const raw = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) throw new Error(`${file}: missing YAML front matter`);
  return { fm: parseYaml(m[1]) as FrontMatter, body: m[2].trim() + '\n' };
}

const coverCache = new Map<string, number>();
export async function coverImage(motif: string): Promise<number> {
  const key = COVER_MOTIFS.includes(motif) ? motif : 'yarn-hook';
  if (coverCache.has(key)) return coverCache.get(key)!;
  const existing = getDb().prepare('SELECT id FROM images WHERE original_name = ?').get(`cover-${key}`) as { id: number } | undefined;
  const id =
    existing?.id ??
    (await storeImage(Buffer.from(coverSvg(key)), { alt: coverAlt(key), license: 'Original illustration generated by this site (owned by the site operator).', originalName: `cover-${key}` }, { trustedSvg: true }));
  coverCache.set(key, id);
  return id;
}

export async function importMarkdownFile(
  file: string,
  opts: { publish?: boolean; publishedAt?: string; aiAssisted?: boolean; validate?: boolean } = {},
): Promise<{ slug: string; status: string; message: string; id?: number }> {
  const { fm, body } = readMarkdown(file);
  if (!fm.slug || !SLUG_RE.test(fm.slug)) return { slug: fm.slug ?? file, status: 'error', message: 'Invalid or missing slug' };
  const category = getCategoryBySlug(fm.category);
  if (!category) return { slug: fm.slug, status: 'error', message: `Unknown category "${fm.category}"` };
  const author = listAuthors()[0];
  const existing = getArticleBySlug(fm.slug);
  const imageId = await coverImage(fm.cover ?? 'yarn-hook');
  const publishedAt = opts.publish ? fm.publishedAt ?? opts.publishedAt ?? existing?.publishedAt ?? nowIso() : null;
  const id = saveArticle(
    {
      slug: fm.slug,
      title: fm.title.trim(),
      excerpt: (fm.excerpt ?? '').trim(),
      contentMd: body,
      categoryId: category.id,
      authorId: existing?.authorId ?? author?.id ?? null,
      featuredImageId: existing?.featuredImageId ?? imageId,
      status: opts.publish ? 'published' : existing?.status ?? 'draft',
      featured: existing?.featured ?? false,
      publishedAt: publishedAt ?? existing?.publishedAt ?? null,
      contentUpdatedAt: existing?.contentUpdatedAt ?? null,
      scheduledFor: null,
      seoTitle: (fm.seoTitle ?? '').trim(),
      metaDescription: (fm.metaDescription ?? '').trim(),
      canonicalUrl: '',
      noindex: false,
      tags: (fm.tags ?? []).map((t) => String(t).toLowerCase().trim()).filter(Boolean),
      faq: (fm.faq ?? []).map((f) => ({ q: String(f.q).trim(), a: String(f.a).trim() })),
      related: (fm.related ?? []).filter((s) => SLUG_RE.test(s)),
      sources: [],
      aiAssisted: fm.aiAssisted ?? opts.aiAssisted ?? existing?.aiAssisted ?? false,
      reviewedBy: fm.reviewedBy ?? existing?.reviewedBy ?? '',
    },
    existing?.id,
  );
  if (opts.validate !== false) {
    const report = validateArticleSync(articleToValidationInput(getArticle(id)!), buildValidationContext(), { requireFeaturedImage: true });
    setValidation(id, report);
    return { slug: fm.slug, status: report.status, message: `${report.errors} errors, ${report.warnings} warnings`, id };
  }
  return { slug: fm.slug, status: 'imported', message: 'ok', id };
}
